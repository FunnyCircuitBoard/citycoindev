#!/usr/bin/env node
/**
 * Writes src/cc-unicode.js: the Unicode 15.1 tables that pin text normalization cc-norm-1 (src/coinmeta-v2.js; Citycoin.dev master v5,
 * stage S22, review finding SF-3). Run it on a runtime whose Unicode version is exactly 15.1 (Node 21.7.x has ICU 74.2), because the
 * tables are read from that runtime's own regular-expression properties:
 *   ASSIGNED        every code point assigned in Unicode 15.1, without controls (Cc), surrogates (Cs) and private use (Co): 149,813, the
 *                   published total of Unicode 15.1
 *   MARK            General_Category M (Mn, Mc, Me) in Unicode 15.1
 *   LETTER_NUMBER   General_Category L or N in Unicode 15.1
 * Usage: node scripts/cc-unicode-table.mjs [out]   (default src/cc-unicode.js). test/coinmeta-v2.test.js checks the committed file.
 * The website never runs this; it only reads the file it wrote. A table for another Unicode version is a new normalization version.
 */
import { writeFileSync } from "node:fs";

if (process.versions.unicode !== "15.1") {
  console.error(`this runtime has Unicode ${process.versions.unicode}; the tables must come from Unicode 15.1 (Node 21.7.x)`);
  process.exit(1);
}
const SETS = {
  ASSIGNED: /^(?![\p{Cc}\p{Cs}\p{Co}])\p{Assigned}$/u,
  MARK: /^\p{M}$/u,
  LETTER_NUMBER: /^[\p{L}\p{N}]$/u,
};
/** Ranges as "gap.length" pairs in base 36 (gap from the end of the previous range, minus one; length minus one), comma separated. */
export function encode(re) {
  const ranges = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c;
    if (!ok && start >= 0) { ranges.push([start, c - 1]); start = -1; }
  }
  let prev = -1;
  const text = ranges.map(([a, b]) => { const s = `${(a - prev - 1).toString(36)}.${(b - a).toString(36)}`; prev = b; return s; }).join(",");
  return { text, count: ranges.reduce((n, [a, b]) => n + b - a + 1, 0), ranges: ranges.length };
}
const out = process.argv[2] || new URL("../src/cc-unicode.js", import.meta.url).pathname;
const t = Object.fromEntries(Object.entries(SETS).map(([k, re]) => [k, encode(re)]));
const src = `/**
 * Unicode 15.1 tables for text normalization cc-norm-1 (src/coinmeta-v2.js; Citycoin.dev master v5, stage S22, review finding SF-3).
 * GENERATED by scripts/cc-unicode-table.mjs on ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}); do not edit by hand.
 * Pinning the version keeps the bytes of a normalized text the same on every runtime: a text made only of code points assigned in
 * Unicode 15.1 has the same NFC form under 15.1 and every later version (Unicode's normalization stability policy), and cc-norm-1 refuses
 * any other code point. Pure data: no route, no setting; no Worker path imports this file.
 *   ASSIGNED        ${t.ASSIGNED.count} code points in ${t.ASSIGNED.ranges} ranges (assigned in 15.1, without Cc, Cs and Co)
 *   MARK            ${t.MARK.count} code points in ${t.MARK.ranges} ranges (General_Category M)
 *   LETTER_NUMBER   ${t.LETTER_NUMBER.count} code points in ${t.LETTER_NUMBER.ranges} ranges (General_Category L or N)
 */
export const UNICODE_VERSION = "15.1";
/** "gap.length" pairs in base 36 (see scripts/cc-unicode-table.mjs) to [[first, last], ...]. */
function decode(text) {
  let prev = -1;
  return Object.freeze(text.split(",").map((p) => { const [g, l] = p.split("."); const a = prev + 1 + parseInt(g, 36); prev = a + parseInt(l, 36); return Object.freeze([a, prev]); }));
}
export const ASSIGNED = decode("${t.ASSIGNED.text}");
export const MARK = decode("${t.MARK.text}");
export const LETTER_NUMBER = decode("${t.LETTER_NUMBER.text}");
/** Is code point \`c\` in \`table\` (sorted, disjoint ranges)? */
export function inTable(table, c) {
  let lo = 0, hi = table.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1, [a, b] = table[mid];
    if (c < a) hi = mid - 1;
    else if (c > b) lo = mid + 1;
    else return true;
  }
  return false;
}
`;
writeFileSync(out, src);
console.log(`wrote ${out}: ${Object.entries(t).map(([k, v]) => `${k} ${v.count} in ${v.ranges} ranges`).join("; ")}`);
